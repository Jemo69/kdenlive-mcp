#!/usr/bin/env python3
"""Generate the static MLT effect/transition catalogue shipped with the package.

Kdenlive describes every built-in effect and transition in ``data/effects`` and
``data/transitions`` as small XML files whose ``tag`` attribute is exactly the
``mlt_service`` string that has to be written into the project file.  Parsing
them once, offline, gives the MCP an authoritative list of valid service names
and parameter names, so a model never has to guess.

Usage::

    python tools/generate_catalog.py /path/to/kdenlive/src > src/kdenlive_mcp/_catalog.py
"""

from __future__ import annotations

import sys
import xml.etree.ElementTree as ET
from pathlib import Path

NS = "{https://www.kdenlive.org}"


def _tag(node: ET.Element) -> str:
    """Local name of an element, with or without the Kdenlive namespace."""
    return node.tag.rsplit("}", 1)[-1]


def _find(node: ET.Element, name: str) -> ET.Element | None:
    """Find a child by local name, ignoring the namespace."""
    for child in node:
        if _tag(child) == name:
            return child
    return None


def _findall(node: ET.Element, name: str) -> list[ET.Element]:
    return [child for child in node if _tag(child) == name]


def _text(node: ET.Element | None) -> str:
    if node is None:
        return ""
    return "".join(node.itertext()).strip()


def _parameters(node: ET.Element) -> dict[str, dict[str, object]]:
    params: dict[str, dict[str, object]] = {}
    for param in _findall(node, "parameter"):
        name = param.get("name")
        if not name:
            continue
        entry: dict[str, object] = {
            "type": param.get("type", "string"),
            "name": _text(_find(param, "name")) or name,
        }
        for key in ("default", "min", "max", "decimals", "factor", "suffix", "paramlist"):
            value = param.get(key)
            if value is not None:
                entry[key] = value
        params[name] = entry
    return params


def collect(root: Path) -> tuple[dict[str, dict], dict[str, dict]]:
    effects: dict[str, dict] = {}
    transitions: dict[str, dict] = {}

    for folder, target, kind in (
        (root / "data" / "effects", effects, "effect"),
        (root / "data" / "transitions", transitions, "transition"),
    ):
        if not folder.exists():
            continue
        for path in sorted(folder.rglob("*.xml")):
            try:
                tree = ET.parse(path)
            except ET.ParseError:
                continue
            for node in tree.getroot().iter():
                tag = _tag(node)
                if tag not in ("effect", "transition"):
                    continue
                service = node.get("tag")
                if not service:
                    continue
                record = {
                    "mlt_service": service,
                    "id": node.get("id", service),
                    "name": _text(_find(node, "name")) or service,
                    "description": _text(_find(node, "description")),
                    "kind": kind,
                    "parameters": _parameters(node),
                }
                target.setdefault(service, record)

    return effects, transitions


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    root = Path(sys.argv[1]).resolve()
    effects, transitions = collect(root)

    print('"""Static MLT effect and transition catalogue.')
    print()
    print("Generated by ``tools/generate_catalog.py`` from the Kdenlive source tree.")
    print("Each entry maps an ``mlt_service`` name to its parameters, exactly as")
    print("Kdenlive itself defines them in ``data/effects`` and ``data/transitions``.")
    print('"""')
    print()
    print("from __future__ import annotations")
    print()
    print("EFFECTS: dict[str, dict] = {")
    for service, record in sorted(effects.items()):
        print(f"    {service!r}: {{")
        print(f"        'mlt_service': {record['mlt_service']!r},")
        print(f"        'name': {record['name']!r},")
        print(f"        'description': {record['description']!r},")
        print(f"        'kind': {record['kind']!r},")
        print(f"        'parameters': {record['parameters']!r},")
        print("    },")
    print("}")
    print()
    print("TRANSITIONS: dict[str, dict] = {")
    for service, record in sorted(transitions.items()):
        print(f"    {service!r}: {{")
        print(f"        'mlt_service': {record['mlt_service']!r},")
        print(f"        'name': {record['name']!r},")
        print(f"        'description': {record['description']!r},")
        print(f"        'kind': {record['kind']!r},")
        print(f"        'parameters': {record['parameters']!r},")
        print("    },")
    print("}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
